'use client'

import { useRef, useEffect, useState } from 'react'
import { Play, X } from 'lucide-react'

const showcaseItems = [
  { title: 'Neural Cityscape', description: 'Futuristic city at golden hour', gradient: 'from-purple-900 via-blue-900 to-indigo-900', size: 'large' },
  { title: 'Style Transfer', description: 'Oil painting to photorealistic', gradient: 'from-rose-900 via-purple-900 to-blue-900', size: 'small' },
  { title: 'Abstract Motion', description: 'Geometric shapes morphing', gradient: 'from-teal-900 via-blue-900 to-purple-900', size: 'small' },
  { title: 'Ocean Dreams', description: 'Cinematic drone footage', gradient: 'from-blue-900 via-teal-900 to-cyan-900', size: 'medium' },
  { title: 'Dance & Motion', description: 'AI motion capture', gradient: 'from-indigo-900 via-purple-900 to-rose-900', size: 'medium' },
]

export default function VideoShowcase() {
  const sectionRef = useRef<HTMLDivElement>(null)
  const [visible, setVisible] = useState(false)
  const [active, setActive] = useState<number | null>(null)

  useEffect(() => {
    const observer = new IntersectionObserver(([e]) => { if (e.isIntersecting) setVisible(true) }, { threshold: 0.1 })
    if (sectionRef.current) observer.observe(sectionRef.current)
    return () => observer.disconnect()
  }, [])

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') setActive(null) }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [])

  return (
    <section id="showcase" ref={sectionRef} className="py-32 px-6 bg-gradient-to-b from-[#0a0a0f] to-[#0f0f1a]">
      <div className="max-w-7xl mx-auto">
        <div className={`text-center mb-20 transition-all duration-700 ${visible ? 'opacity-100 translate-y-0' : 'opacity-0 translate-y-8'}`}>
          <div className="inline-block bg-blue-600/10 border border-blue-500/20 rounded-full px-4 py-1.5 text-blue-400 text-sm font-medium mb-6">
            Generated by Higgsfield AI
          </div>
          <h2 className="text-4xl md:text-6xl font-bold text-white mb-6">
            See what&apos;s <span className="text-gradient">possible</span>
          </h2>
          <p className="text-xl text-white/50 max-w-2xl mx-auto">
            Every video below was created by AI in under 30 seconds. No cameras, no crew, no editing.
          </p>
        </div>

        <div className="grid grid-cols-2 md:grid-cols-3 gap-4 auto-rows-[200px]">
          {showcaseItems.map((item, i) => (
            <div
              key={item.title}
              className={`relative rounded-2xl overflow-hidden cursor-pointer group transition-all duration-700 ${
                visible ? 'opacity-100 scale-100' : 'opacity-0 scale-95'
              } ${item.size === 'large' ? 'row-span-2 col-span-1 md:col-span-1' : ''}`}
              style={{ transitionDelay: `${i * 120}ms` }}
              onClick={() => setActive(i)}
            >
              <div className={`absolute inset-0 bg-gradient-to-br ${item.gradient}`} />
              <div className="absolute inset-0 opacity-20 bg-[radial-gradient(ellipse_at_center,_rgba(255,255,255,0.3)_0%,_transparent_70%)] group-hover:opacity-40 transition-opacity" />

              <div className="absolute inset-0 flex flex-col items-center justify-center opacity-0 group-hover:opacity-100 transition-opacity duration-300">
                <div className="w-14 h-14 bg-white/20 backdrop-blur-sm rounded-full flex items-center justify-center mb-3 border border-white/30">
                  <Play className="w-6 h-6 text-white ml-1" />
                </div>
              </div>

              <div className="absolute bottom-0 left-0 right-0 p-4 bg-gradient-to-t from-black/80 to-transparent">
                <h3 className="text-white font-semibold text-sm">{item.title}</h3>
                <p className="text-white/50 text-xs">{item.description}</p>
              </div>

              <div className="absolute top-3 right-3 bg-black/40 backdrop-blur-sm rounded-full px-2.5 py-0.5 text-xs text-white/70 border border-white/10">
                AI Generated
              </div>
            </div>
          ))}
        </div>

        {active !== null && (
          <div
            className="fixed inset-0 z-50 bg-black/90 backdrop-blur-xl flex items-center justify-center p-6"
            onClick={() => setActive(null)}
          >
            <button className="absolute top-6 right-6 text-white/60 hover:text-white transition-colors">
              <X className="w-8 h-8" />
            </button>
            <div
              className={`relative w-full max-w-3xl aspect-video rounded-2xl overflow-hidden bg-gradient-to-br ${showcaseItems[active].gradient}`}
              onClick={(e) => e.stopPropagation()}
            >
              <div className="absolute inset-0 flex items-center justify-center">
                <p className="text-white/60 text-center">
                  <span className="block text-2xl font-bold text-white mb-2">{showcaseItems[active].title}</span>
                  <span className="text-sm">Video generated by Higgsfield AI</span>
                </p>
              </div>
            </div>
          </div>
        )}
      </div>
    </section>
  )
}
